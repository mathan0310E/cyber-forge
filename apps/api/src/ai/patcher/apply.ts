import { isProtectedPath, isSafeRelativePath, type PatchOperation } from '@wolf-forge/shared-types';
import { ApiError } from '../../services/errors.js';

export interface ValidatedPatch {
  operations: PatchOperation[];
  /** Paths that were silently dropped because they duplicate or no-op. */
  skipped: string[];
}

/**
 * Validates a patch before any of it is applied.
 *
 * Validation is all-or-nothing: if any operation is unsafe the whole patch is
 * rejected, so a partially applied patch can never leave a project in a state
 * the model did not intend.
 */
export function validatePatch(
  operations: PatchOperation[],
  options: {
    /** Files the project currently has, used to reject pointless deletes. */
    existingPaths: ReadonlySet<string>;
    /** Cap on total bytes the patch may write. */
    maxTotalBytes: number;
    /** Scaffold-owned files that the AI must not overwrite. */
    ownedPaths?: ReadonlySet<string>;
    /** When false, `delete` operations are refused. */
    allowDelete?: boolean;
  },
): ValidatedPatch {
  if (operations.length === 0) {
    throw ApiError.badRequest('The patch contained no operations.');
  }

  const seen = new Set<string>();
  const skipped: string[] = [];
  const valid: PatchOperation[] = [];
  let totalBytes = 0;

  for (const op of operations) {
    if (!isSafeRelativePath(op.path)) {
      throw ApiError.badRequest(
        `Patch rejected: unsafe file path ${JSON.stringify(op.path).slice(0, 120)}. ` +
          'Paths must be project-relative with no "..", no leading slash and no backslashes.',
      );
    }
    if (isProtectedPath(op.path)) {
      throw ApiError.badRequest(
        `Patch rejected: ${op.path} is a protected path. Generated changes may never touch ` +
          'environment files, credentials, VCS data or installed dependencies.',
      );
    }
    if (seen.has(op.path)) {
      throw ApiError.badRequest(
        `Patch rejected: ${op.path} appears more than once in the same patch.`,
      );
    }
    seen.add(op.path);

    if (op.op === 'write') {
      const bytes = Buffer.byteLength(op.content, 'utf8');
      totalBytes += bytes;
      if (totalBytes > options.maxTotalBytes) {
        throw ApiError.tooLarge(
          `Patch rejected: writing these files would exceed the ${Math.round(
            options.maxTotalBytes / 1000,
          )} kB per-change limit. Ask for a smaller change.`,
        );
      }
      if (options.ownedPaths?.has(op.path)) {
        throw ApiError.badRequest(
          `Patch rejected: ${op.path} is generated by the Wolf Forge scaffold and cannot be ` +
            'overwritten, because doing so would break the project build.',
        );
      }
      valid.push(op);
      continue;
    }

    // delete
    if (options.allowDelete === false) {
      throw ApiError.badRequest('Patch rejected: this operation does not permit file deletion.');
    }
    if (options.ownedPaths?.has(op.path)) {
      throw ApiError.badRequest(`Patch rejected: ${op.path} is required by the scaffold.`);
    }
    if (!options.existingPaths.has(op.path)) {
      skipped.push(op.path);
      continue;
    }
    valid.push(op);
  }

  if (valid.length === 0) {
    throw ApiError.badRequest(
      'Patch rejected: none of the requested operations would change the project.',
    );
  }

  return { operations: valid, skipped };
}

/**
 * Applies a validated patch to an in-memory file map. Returns a new map; the
 * input is never mutated, so a failed later step cannot corrupt the source.
 */
export function applyPatch(
  files: ReadonlyMap<string, string>,
  patch: ValidatedPatch,
): Map<string, string> {
  const next = new Map(files);
  for (const op of patch.operations) {
    if (op.op === 'write') {
      next.set(op.path, op.content);
    } else {
      next.delete(op.path);
    }
  }
  return next;
}

/** Short human summary of a patch, used for the version history entry. */
export function describePatch(patch: ValidatedPatch): string {
  const writes = patch.operations.filter((o) => o.op === 'write').length;
  const deletes = patch.operations.filter((o) => o.op === 'delete').length;
  const parts: string[] = [];
  if (writes > 0) parts.push(`${writes} file${writes === 1 ? '' : 's'} written`);
  if (deletes > 0) parts.push(`${deletes} file${deletes === 1 ? '' : 's'} removed`);
  if (patch.skipped.length > 0) parts.push(`${patch.skipped.length} no-op skipped`);
  return parts.join(', ');
}
