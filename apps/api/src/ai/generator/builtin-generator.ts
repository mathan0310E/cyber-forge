import type { ProjectCategory, WebsiteSpec } from '@wolf-forge/shared-types';
import { buildThemeCss, escapeText, toComponentName } from './scaffold.js';
import {
  templateFor,
  type PagePlan,
  type SectionPlan,
  type TemplateDefinition,
} from './templates.js';

/**
 * The built-in template engine.
 *
 * Produces a complete, buildable project from a template definition. This is a
 * real generator, not a stub: the output installs, builds and serves.
 */

export interface BuiltinGeneration {
  files: Array<{ path: string; content: string }>;
  summary: string;
}

export function generateFromTemplate(input: {
  spec: WebsiteSpec;
  category: ProjectCategory;
}): BuiltinGeneration {
  const template = templateFor(input.category);
  if (input.spec.framework === 'static-html') {
    return generateStatic(template, input.spec);
  }
  return generateReact(template, input.spec);
}

/* -------------------------------------------------------------------------- */
/* React + Vite output                                                        */
/* -------------------------------------------------------------------------- */

function generateReact(template: TemplateDefinition, spec: WebsiteSpec): BuiltinGeneration {
  const files: Array<{ path: string; content: string }> = [
    { path: 'src/components/Section.tsx', content: sectionComponent() },
    { path: 'src/components/Card.tsx', content: cardComponent() },
    { path: 'src/components/ContactForm.tsx', content: contactFormComponent() },
    { path: 'src/components/SampleContentNotice.tsx', content: sampleNoticeComponent() },
    { path: 'src/styles/theme.css', content: `${buildThemeCss(spec)}${layoutCss(spec)}` },
  ];

  for (const page of template.pages) {
    files.push({
      path: `src/pages/${toComponentName(page.name)}.tsx`,
      content: renderPage(page),
    });
  }

  return {
    files,
    summary:
      `Generated a ${template.label.toLowerCase()} from the built-in template engine ` +
      `(${template.pages.length} page${template.pages.length === 1 ? '' : 's'}).`,
  };
}

function renderPage(page: PagePlan): string {
  const component = toComponentName(page.name);
  const imports = new Set<string>();
  const body = page.sections.map((s) => renderSection(s, imports));

  const importLines = [
    `import { Section } from '../components/Section';`,
    ...(imports.has('Card') ? [`import { Card } from '../components/Card';`] : []),
    ...(imports.has('ContactForm')
      ? [`import { ContactForm } from '../components/ContactForm';`]
      : []),
    ...(imports.has('SampleContentNotice')
      ? [`import { SampleContentNotice } from '../components/SampleContentNotice';`]
      : []),
  ];

  return `${importLines.join('\n')}

/**
 * ${page.purpose}
 *
 * Placeholder copy in this file is sample content generated by Wolf Forge.
 * Replace it with your own before publishing.
 */
export function ${component}() {
  return (
    <>
${body.join('\n')}
    </>
  );
}
`;
}

function renderSection(section: SectionPlan, imports: Set<string>): string {
  const heading = jsxText(section.heading);
  const body = jsxText(section.body);
  const cards = section.items
    .map((i) => `          <Card title="${jsxText(i.title)}">${jsxText(i.body)}</Card>`)
    .join('\n');

  switch (section.kind) {
    case 'hero':
      return `      <section className="wf-hero">
        <h1>${heading}</h1>
        <p className="wf-lede">${body}</p>
        <div className="wf-actions">
${section.items
  .map((i) => `          <a className="wf-button" href="#/contact">${jsxText(i.title)}</a>`)
  .join('\n')}
        </div>
      </section>`;

    case 'contact':
      imports.add('ContactForm');
      return `      <Section heading="${heading}" intro="${body}">
        <ContactForm />
      </Section>`;

    case 'cta':
      imports.add('SampleContentNotice');
      return `      <section className="wf-cta">
        <h2>${heading}</h2>
        <p>${body}</p>
        <a className="wf-button" href="#/contact">Get in touch</a>
        <SampleContentNotice />
      </section>`;

    case 'gallery':
    case 'products':
    case 'posts':
    case 'features':
    case 'pricing':
    case 'schedule':
    case 'steps':
    case 'faq': {
      imports.add('Card');
      const columns = section.kind === 'faq' ? 2 : 3;
      return `      <Section heading="${heading}" intro="${body}">
        <div className="wf-grid wf-grid-${columns}">
${cards}
        </div>
      </Section>`;
    }

    case 'about':
    default:
      return `      <Section heading="${heading}" intro="${body}" />`;
  }
}

function sectionComponent(): string {
  return `import type { ReactNode } from 'react';

export function Section({
  heading,
  intro,
  children,
}: {
  heading: string;
  intro?: string;
  children?: ReactNode;
}) {
  return (
    <section className="wf-section">
      <h2>{heading}</h2>
      {intro ? <p className="wf-lede">{intro}</p> : null}
      {children}
    </section>
  );
}
`;
}

function cardComponent(): string {
  return `import type { ReactNode } from 'react';

export function Card({ title, children }: { title: string; children?: ReactNode }) {
  return (
    <article className="wf-card">
      <h3>{title}</h3>
      {children ? <p>{children}</p> : null}
    </article>
  );
}
`;
}

function contactFormComponent(): string {
  return `import { useState, type FormEvent } from 'react';

interface Errors {
  name?: string;
  email?: string;
  message?: string;
}

/**
 * Contact form with client-side validation.
 *
 * There is no backend wired up: submitting shows a confirmation message. Replace
 * the submit handler with a real endpoint before publishing.
 */
export function ContactForm() {
  const [name, setName] = useState('');
  const [email, setEmail] = useState('');
  const [message, setMessage] = useState('');
  const [errors, setErrors] = useState<Errors>({});
  const [sent, setSent] = useState(false);

  function validate(): Errors {
    const next: Errors = {};
    if (name.trim().length < 2) next.name = 'Please enter your name.';
    if (!/^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$/.test(email.trim())) {
      next.email = 'Please enter a valid email address.';
    }
    if (message.trim().length < 10) {
      next.message = 'Please write at least 10 characters.';
    }
    return next;
  }

  function onSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const found = validate();
    setErrors(found);
    if (Object.keys(found).length > 0) return;
    setSent(true);
  }

  if (sent) {
    return (
      <p role="status" className="wf-notice">
        Thanks — your message has been captured. Connect a real endpoint to receive it.
      </p>
    );
  }

  return (
    <form className="wf-form" onSubmit={onSubmit} noValidate>
      <div className="wf-field">
        <label htmlFor="wf-name">Name</label>
        <input
          id="wf-name"
          name="name"
          value={name}
          onChange={(e) => setName(e.target.value)}
          aria-invalid={errors.name ? true : undefined}
          aria-describedby={errors.name ? 'wf-name-error' : undefined}
        />
        {errors.name ? (
          <p className="wf-error" id="wf-name-error">
            {errors.name}
          </p>
        ) : null}
      </div>

      <div className="wf-field">
        <label htmlFor="wf-email">Email</label>
        <input
          id="wf-email"
          name="email"
          type="email"
          value={email}
          onChange={(e) => setEmail(e.target.value)}
          aria-invalid={errors.email ? true : undefined}
          aria-describedby={errors.email ? 'wf-email-error' : undefined}
        />
        {errors.email ? (
          <p className="wf-error" id="wf-email-error">
            {errors.email}
          </p>
        ) : null}
      </div>

      <div className="wf-field">
        <label htmlFor="wf-message">Message</label>
        <textarea
          id="wf-message"
          name="message"
          rows={5}
          value={message}
          onChange={(e) => setMessage(e.target.value)}
          aria-invalid={errors.message ? true : undefined}
          aria-describedby={errors.message ? 'wf-message-error' : undefined}
        />
        {errors.message ? (
          <p className="wf-error" id="wf-message-error">
            {errors.message}
          </p>
        ) : null}
      </div>

      <button className="wf-button" type="submit">
        Send message
      </button>
    </form>
  );
}
`;
}

