function generateStatic(template: TemplateDefinition, spec: WebsiteSpec): BuiltinGeneration {
  const sections = template.pages
    .flatMap((page) => page.sections.map((s) => renderStaticSection(s, page.name)))
    .join('\n');

  const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${escapeText(spec.title)}</title>
    <meta name="description" content="${escapeText(spec.description)}" />
    <link rel="stylesheet" href="./styles.css" />
  </head>
  <body>
    <header class="wf-nav">
      <a class="wf-brand" href="./index.html">${escapeText(spec.title)}</a>
      <nav aria-label="Main">
${template.pages
  .map(
    (p) =>
      `        <a class="wf-nav-link" href="#${escapeText(p.name.toLowerCase())}">${escapeText(p.name)}</a>`,
  )
  .join('\n')}
      </nav>
    </header>

    <main id="main">
${sections}
    </main>

    <footer class="wf-footer">
      <p>${escapeText(spec.title)} — built with Wolf Forge. Sample content should be replaced.</p>
    </footer>
  </body>
</html>
`;

  return {
    files: [
      { path: 'index.html', content: html },
      { path: 'styles.css', content: `${buildThemeCss(spec)}${layoutCss(spec)}` },
    ],
    summary:
      `Generated a ${template.label.toLowerCase()} from the built-in template engine ` +
      '(single static page, no build step).',
  };
}

function renderStaticSection(section: SectionPlan, pageName: string): string {
  const heading = escapeText(section.heading);
  const body = escapeText(section.body);
  const anchor = ` id="${escapeText(pageName.toLowerCase())}"`;

  if (section.kind === 'hero') {
    return `      <section class="wf-hero"${anchor}>
        <h1>${heading}</h1>
        <p class="wf-lede">${body}</p>
      </section>`;
  }

  if (section.kind === 'contact') {
    return `      <section class="wf-section"${anchor}>
        <h2>${heading}</h2>
        <p class="wf-lede">${body}</p>
        <form class="wf-form" action="#" method="post">
          <div class="wf-field">
            <label for="static-name">Name</label>
            <input id="static-name" name="name" required />
          </div>
          <div class="wf-field">
            <label for="static-email">Email</label>
            <input id="static-email" name="email" type="email" required />
          </div>
          <div class="wf-field">
            <label for="static-message">Message</label>
            <textarea id="static-message" name="message" rows="5" required></textarea>
          </div>
          <button class="wf-button" type="submit">Send message</button>
        </form>
        <p class="wf-sample-notice" role="note">This form is not connected to a backend yet.</p>
      </section>`;
  }

  const cards =
    section.items.length > 0
      ? `        <div class="wf-grid wf-grid-3">
${section.items
  .map(
    (i) =>
      `          <article class="wf-card"><h3>${escapeText(i.title)}</h3><p>${escapeText(i.body)}</p></article>`,
  )
  .join('\n')}
        </div>`
      : '';

  return `      <section class="wf-section"${anchor}>
        <h2>${heading}</h2>
        <p class="wf-lede">${body}</p>
${cards}
      </section>`;
}

/** Escapes text for safe inclusion inside a JSX attribute or text node. */
function jsxText(input: string): string {
  return input.replace(/[{}<>]/g, '').replace(/"/g, "'").trim();
}
